#!/usr/bin/env python3
"""Generate/check the exact compact-tag table and compare its actual C++ lookup."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
NATIVE = ROOT / "UniXNU-zorn/native/ufs-read"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate the checked-in tag header")
    parser.add_argument("--output", type=Path, default=ROOT / "out/zorn/trace-stage-host-checks.json")
    args = parser.parse_args()
    canonical = NATIVE / "trace-stages.json"
    tags = json.loads(canonical.read_text())["stages"]
    assert len(tags) == len(set(tags)) and all(0 < len(t.encode("ascii")) <= 7 for t in tags)
    rows = sorted((int.from_bytes(t.encode(), "little"), t) for t in tags)
    generated = '''// SPDX-License-Identifier: BSD-2-Clause-Patent
// Generated by check-zorn-trace-stages.py --write from trace-stages.json.
#pragma once
#include <stdint.h>
static const uint64_t zorn_trace_stage_keys[] = {
'''
    generated += "".join(f"    0x{key:016x}ULL, // {tag}\n" for key, tag in rows)
    generated += '''};
enum { ZORN_TRACE_STAGE_COUNT = sizeof(zorn_trace_stage_keys) / sizeof(zorn_trace_stage_keys[0]) };
static inline int zorn_trace_stage_index(const char *text)
{
    if (!text) return -1;
    uint64_t key = 0;
    unsigned length = 0;
    for (; length < 8 && text[length]; ++length)
        key |= (uint64_t)(uint8_t)text[length] << (length * 8);
    if (length == 8) return -1; // Known tags are at most seven bytes; do not match a prefix.
    unsigned low = 0, high = ZORN_TRACE_STAGE_COUNT;
    while (low < high) {
        unsigned mid = low + (high - low) / 2;
        if (zorn_trace_stage_keys[mid] < key) low = mid + 1;
        else high = mid;
    }
    return low < ZORN_TRACE_STAGE_COUNT && zorn_trace_stage_keys[low] == key ? (int)low : -1;
}
'''
    header = NATIVE / "ZornTraceStages.h"
    if args.write:
        header.write_text(generated)
    assert header.read_text() == generated, "regenerate the tag header from its canonical list"
    harness = r'''
#include <cassert>
#include <cstring>
#include <string>
#include "ZornTraceStages.h"
static const char *reference[] = {@TAGS@};
static void check(const char *text) {
    bool found = false;
    for (const char *tag : reference) if (!strcmp(tag, text)) { found = true; break; }
    int index = zorn_trace_stage_index(text);
    assert((index >= 0) == found);
    assert(index < ZORN_TRACE_STAGE_COUNT);
}
int main() {
    assert(zorn_trace_stage_index(nullptr) == -1);
    bool seen[ZORN_TRACE_STAGE_COUNT] = {};
    for (const char *tag : reference) {
        check(tag);
        const int index = zorn_trace_stage_index(tag);
        assert(!seen[index]); seen[index] = true;
        std::string s(tag);
        for (unsigned i = 0; i < s.size(); ++i) check(s.substr(0, i).c_str());
        check((s + "0").c_str()); check((s + "XXXXXXXXX").c_str());
        for (unsigned i = 0; i < s.size(); ++i) {
            std::string changed(s); changed[i] ^= 1; check(changed.c_str());
        }
    }
    uint32_t random = 0x92988a43;
    for (unsigned n = 0; n < 100000; ++n) {
        random = random * 1664525U + 1013904223U;
        std::string s;
        for (unsigned i = 0, len = random % 24; i < len; ++i) {
            random = random * 1664525U + 1013904223U;
            s += char(1 + random % 255);
        }
        check(s.c_str());
    }
}
'''.replace("@TAGS@", ",".join(json.dumps(t) for t in tags))
    with tempfile.TemporaryDirectory(prefix="zorn-trace-tags-") as directory:
        cpp = Path(directory) / "check.cpp"
        executable = Path(directory) / "check"
        cpp.write_text(harness)
        subprocess.run(["xcrun", "clang++", "-O2", "-std=c++17", "-Wall", "-Wextra", "-Werror",
                        "-I", str(NATIVE), str(cpp), "-o", str(executable)], check=True)
        subprocess.run([str(executable)], check=True)
    source = (NATIVE / "ZornUfsRead.cpp").read_text()
    assert 'if (gCompactTrace && strcmp(text, gRecoveryCheckpoint) != 0)' in source
    if not args.write:
        assert '#include "ZornTraceStages.h"' in source and 'int stage = zorn_trace_stage_index(text);' in source
    report = {"canonical_sha256": hashlib.sha256(canonical.read_bytes()).hexdigest(),
              "actual_header_sha256": hashlib.sha256(header.read_bytes()).hexdigest(),
              "exact_original_tags": len(tags), "max_tag_bytes": 7,
              "unknown_inputs_tested": 100000, "prefixes_and_mutations_tested": True,
              "selected_checkpoint_bypass_retained": True, "hardware_qualified": False}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
